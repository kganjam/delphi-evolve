"""Unsigned TriG nanopub DRAFTS for claim-use and evidence-reuse records.

Same vocabulary as artifacts/evidence/nanopubs (temporary purl.org/nanopub/temp URIs,
`de:signatureStatus "UNSIGNED DRAFT"`). Nothing here is a trusty URI, nothing is published
to a nanopub network, and no scientist identity or endorsement is asserted. The Delphi
claim being USED keeps its own published IRI/nanopub; the draft only records the use.
"""
from __future__ import annotations

import json

PREFIXES = """@prefix this: <http://purl.org/nanopub/temp/delphi-evolve/claim-reuse/{name}> .
@prefix sub: <http://purl.org/nanopub/temp/delphi-evolve/claim-reuse/{name}/> .
@prefix np: <http://www.nanopub.org/nschema#> .
@prefix npx: <http://purl.org/nanopub/x/> .
@prefix prov: <http://www.w3.org/ns/prov#> .
@prefix dct: <http://purl.org/dc/terms/> .
@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .
@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .
@prefix delphi: <https://w3id.org/delphi/ontology/> .
@prefix de: <urn:x-delphi-evolve:vocab#> .

"""


def lit(s) -> str:
    return json.dumps(str(s), ensure_ascii=False)


def draft(name: str, label: str, assertion: str, derived_from: list, created: str, note: str) -> str:
    derived = "".join(f"  sub:assertion prov:wasDerivedFrom <{u}> .\n" for u in derived_from)
    return PREFIXES.format(name=name) + f"""sub:Head {{
  this: a np:Nanopublication ;
    np:hasAssertion sub:assertion ;
    np:hasProvenance sub:provenance ;
    np:hasPublicationInfo sub:pubinfo .
}}

sub:assertion {{
{assertion}
}}

sub:provenance {{
  sub:assertion prov:wasAttributedTo sub:softwareAgent ;
    prov:wasGeneratedBy sub:generation .
  sub:softwareAgent a prov:SoftwareAgent ;
    rdfs:label "claim_runtime (software; model Claude Sonnet 5.5 authored the adapter)" .
  sub:generation a prov:Activity ;
    prov:wasAssociatedWith sub:softwareAgent ;
    rdfs:comment {lit(note)} .
{derived}}}

sub:pubinfo {{
  this: dct:created "{created}"^^xsd:dateTime ;
    rdfs:label {lit(label)} ;
    npx:hasNanopubType de:ClaimUse ;
    de:signatureStatus "UNSIGNED DRAFT: no trusty URI assigned, not published to any nanopub network" ;
    rdfs:comment "Draft only. Records a software use of an existing Delphi claim; it does not republish or endorse that claim." .
}}
"""


def claim_use_trig(name: str, resp: dict, created: str) -> str:
    cu = resp.get("claim_use", {})
    nps = cu.get("nanopubs") or []
    a = [f"  sub:use a de:ClaimUse ;",
         f"    rdfs:label {lit('Use of ' + cu.get('iri', '?') + ' by ' + resp.get('adapter', {}).get('id', '?'))} ;",
         f"    de:usesClaim <{cu.get('iri', 'urn:x-unknown')}> ;",
         f"    de:delphiSource {lit(cu.get('delphi_source'))} ;",
         f"    de:claimRecordResponseSha256 {lit(cu.get('record_response_sha256'))} ;",
         f"    de:adapterId {lit(resp.get('adapter', {}).get('id'))} ;",
         f"    de:adapterVersion {lit(resp.get('adapter', {}).get('version'))} ;",
         f"    de:adapterSourceSha256 {lit(resp.get('adapter', {}).get('source_sha256'))} ;",
         f"    de:requestSha256 {lit(resp['request_sha256'])} ;",
         f"    de:responseSha256 {lit(resp['response_sha256'])} ;",
         f"    de:decision {lit(resp['decision'])} ;",
         f"    de:reasonCode {lit(resp['reason_code'])} ;",
         f"    de:epistemicStatus {lit(resp.get('epistemic_status', 'none: computation refused'))} ."]
    return draft(name, "Draft: claim use record " + name, "\n".join(a), nps, created,
                 "Generated by `python -m claim_runtime demo`; see repository commit for the exact code.")


def evidence_reuse_trig(name: str, decision: dict, claim: dict | None, created: str) -> str:
    a = [f"  sub:reuse a de:EvidenceReuse ;",
         f"    rdfs:label {lit('Evidence reuse decision: ' + decision['decision'])} ;",
         f"    de:decision {lit(decision['decision'])} ;",
         f"    de:reason {lit(decision['reason'])}" + (" ;" if claim else " .")]
    if claim:
        a += [f"    de:evidenceId {lit(claim['id'])} ;",
              f"    de:evidenceKind {lit(claim['kind'])} ;",
              f"    de:subjectGenotype {lit(claim['subject'])} ;",
              f"    de:datasetSha256 {lit(claim['dataset_sha256'])} ;",
              f"    de:assayContextId {lit(claim['assay_context_id'])} ;",
              f"    de:referenceSha256 {lit(claim['reference_sha256'])} ;",
              f"    de:units {lit(claim['units'])} ;",
              f"    de:observedScoreMicro {int(claim['value'].get('score_micro', 0))} ."]
    return draft(name, "Draft: evidence reuse " + name, "\n".join(a),
                 ["https://data.caltech.edu/records/h5rah-5z170"], created,
                 "Generated by `python -m claim_runtime demo`; the value is an OBSERVED source-table score, reused, not newly measured.")
